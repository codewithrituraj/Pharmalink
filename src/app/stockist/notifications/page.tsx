"use client"

import { useMemo, useState } from "react"
import { BellOff, CheckCheck, Filter } from "lucide-react"

import { PageHeader } from "@/components/page-header"
import { CardSkeleton } from "@/components/skeletons"
import { Button } from "@/components/ui/button"
import { Card, CardContent } from "@/components/ui/card"
import { useNotifications } from "@/hooks/use-notifications"
import {
  NOTIFICATION_TYPES,
  NotificationEmptyState,
  NotificationRow,
} from "@/components/notifications/notification-row"

export default function NotificationsPage() {
  const { notifications, unread, status, error, loading, markRead, markAllRead, refresh, serverTime } =
    useNotifications()
  const [type, setType] = useState("all")
  const [unreadOnly, setUnreadOnly] = useState(false)

  const visible = useMemo(
    () =>
      notifications.filter((notification) => {
        if (type !== "all" && notification.type !== type) return false
        if (unreadOnly && notification.readAt) return false
        return true
      }),
    [notifications, type, unreadOnly],
  )

  const grouped = useMemo(() => {
    const sections: { label: string; items: typeof visible }[] = [
      { label: "Newest", items: [] },
      { label: "Earlier", items: [] },
    ]
    const cutoff = new Date(serverTime).getTime() - 86_400_000
    for (const notification of visible) {
      const bucket = new Date(notification.createdAt).getTime() >= cutoff ? sections[0] : sections[1]
      bucket.items.push(notification)
    }
    return sections.filter((section) => section.items.length > 0)
  }, [visible, serverTime])

  return (
    <div className="space-y-6">
      <PageHeader
        title="Notification centre"
        description="Expiry warnings, low-stock signals, scheme opportunities and order updates. Alerts are generated by the daily supply-alert job and delivered to this browser as they happen."
        actions={
          <div className="flex flex-wrap items-center gap-2">
            <span className="rounded-full border border-border px-3 py-1.5 text-xs text-muted-foreground">
              {status === "live" ? "Live connection" : status === "polling" ? "Polling every minute" : "Connecting…"}
            </span>
            <Button variant="outline" onClick={refresh}>
              Refresh
            </Button>
            <Button onClick={markAllRead} disabled={unread === 0}>
              <CheckCheck className="size-4" /> Mark all read
            </Button>
          </div>
        }
        meta={
          unread > 0 ? (
            <span className="rounded-full bg-primary/10 px-3 py-1 text-xs font-medium text-primary">
              {unread} unread
            </span>
          ) : (
            <span className="text-xs text-muted-foreground">No unread alerts</span>
          )
        }
      />

      {error ? (
        <Card className="border-destructive/40 bg-destructive/5">
          <CardContent className="flex flex-wrap items-center justify-between gap-3 py-4">
            <p className="text-sm text-destructive">{error}</p>
            <Button size="sm" variant="outline" onClick={refresh}>
              Try again
            </Button>
          </CardContent>
        </Card>
      ) : null}

      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div className="flex flex-wrap items-center gap-1.5" role="group" aria-label="Filter by alert type">
          <Filter className="size-4 text-muted-foreground" aria-hidden />
          {NOTIFICATION_TYPES.slice(0, 6).map((option) => (
            <Button
              key={option.value}
              size="sm"
              variant={type === option.value ? "default" : "outline"}
              onClick={() => setType(option.value)}
            >
              {option.label}
            </Button>
          ))}
        </div>
        <Button
          size="sm"
          variant={unreadOnly ? "default" : "outline"}
          onClick={() => setUnreadOnly((value) => !value)}
          aria-pressed={unreadOnly}
        >
          <BellOff className="size-3.5" /> Unread only
        </Button>
      </div>

      {loading ? (
        <CardSkeleton />
      ) : visible.length === 0 ? (
        <Card className="surface-card border-0">
          <CardContent className="p-0">
            <NotificationEmptyState />
          </CardContent>
        </Card>
      ) : (
        <div className="space-y-6">
          {grouped.map((section) => (
            <section key={section.label} className="space-y-3">
              <h2 className="eyebrow">{section.label}</h2>
              <Card className="surface-card border-0 p-0">
                <ul className="divide-y divide-border">
                  {section.items.map((notification) => (
                    <NotificationRow
                      key={notification.id}
                      notification={notification}
                      onRead={markRead}
                    />
                  ))}
                </ul>
              </Card>
            </section>
          ))}
        </div>
      )}

      <p className="text-xs leading-5 text-muted-foreground">
        Alerts are generated server-side from your inventory, delivered purchase orders and demand history.
        Nothing is sent to a third-party service.
      </p>
    </div>
  )
}
